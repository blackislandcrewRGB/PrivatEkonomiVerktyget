/** The source of web/src/generated/brandIcons.ts for a list of simple-icons slugs (see scripts/gen-brand-icons.ts). */
export async function brandIconsModule(slugs: string[]): Promise<string> {
  type Icon = { slug: string; title: string; hex: string; path: string };
  const icons = (Object.values(await import("simple-icons")) as unknown[]).filter((i): i is Icon => typeof i === "object" && i !== null && "slug" in i);
  const bySlug = new Map(icons.map((i) => [i.slug, i]));
  const missing = slugs.filter((s) => !bySlug.has(s));
  if (missing.length) throw new Error(`Finns inte i simple-icons: ${missing.join(", ")}`);
  const entries = [...slugs]
    .sort()
    .map((s) => {
      const i = bySlug.get(s)!;
      return `  ${JSON.stringify(s)}: { title: ${JSON.stringify(i.title)}, hex: "#${i.hex}", path: ${JSON.stringify(i.path)} },`;
    });
  return [
    "// Generated by scripts/gen-brand-icons.ts from simple-icons (CC0). Do not edit.",
    "export interface BrandIcon {",
    "  title: string;",
    "  hex: string;",
    "  /** SVG path in a 24×24 viewBox. */",
    "  path: string;",
    "}",
    "",
    "export const BRAND_ICONS: Record<string, BrandIcon> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}
